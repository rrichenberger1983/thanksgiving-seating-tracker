// Turns src/data/layout-raw.json (measured from the four floor-plan photos)
// into stable table IDs + normalized coordinates, then writes:
//   src/data/layout.json            (used by tests / reference)
//   supabase/migrations/0002_seed_tables.sql
//   supabase/setup.sql              (0001 + 0002 + 0003, paste-once script)
// Numbering rule: rows are bands of 200 px (floor(cy/200)), top to bottom;
// inside a band, left to right. IDs are zero-padded: MD-01, AR-01, 200-01, ES-01.
import fs from 'node:fs';

const raw = JSON.parse(fs.readFileSync('src/data/layout-raw.json', 'utf8'));
const { w: CW, h: CH } = raw.canvas;
const r4 = (n) => Math.round(n * 10000) / 10000;

const areas = [];
const tables = [];
for (const room of raw.rooms) {
  areas.push({ id: room.id, name: room.name, sort_order: room.sort, map_w: CW, map_h: CH });
  const sorted = room.tables
    .map(([cx, cy, w, h, shape]) => ({ cx, cy, w, h, shape }))
    .sort((a, b) => Math.floor(a.cy / 200) - Math.floor(b.cy / 200) || a.cx - b.cx);
  sorted.forEach((t, i) => {
    const num = String(i + 1).padStart(2, '0');
    tables.push({
      id: `${room.prefix}-${num}`, area_id: room.id, label: num, shape: t.shape,
      x: r4(t.cx / CW), y: r4(t.cy / CH), w: r4(t.w / CW), h: r4(t.h / CH),
    });
  });
}
fs.writeFileSync('src/data/layout.json', JSON.stringify({ areas, tables }, null, 2) + '\n');

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
let sql = '-- GENERATED by scripts/build-layout.mjs — do not edit by hand.\n';
sql += 'insert into public.dining_areas (id, name, sort_order, map_w, map_h) values\n';
sql += areas.map((a) => `  (${q(a.id)}, ${q(a.name)}, ${a.sort_order}, ${a.map_w}, ${a.map_h})`).join(',\n');
sql += '\non conflict (id) do nothing;\n\n';
sql += 'insert into public.dining_tables (id, area_id, label, shape, x, y, w, h) values\n';
sql += tables.map((t) => `  (${q(t.id)}, ${q(t.area_id)}, ${q(t.label)}, ${q(t.shape)}, ${t.x}, ${t.y}, ${t.w}, ${t.h})`).join(',\n');
sql += '\non conflict (id) do nothing;\n';
fs.mkdirSync('supabase/migrations', { recursive: true });
fs.writeFileSync('supabase/migrations/0002_seed_tables.sql', sql);

const parts = ['0001_schema.sql', '0002_seed_tables.sql'].filter((f) => fs.existsSync(`supabase/migrations/${f}`));
fs.writeFileSync('supabase/setup.sql', parts.map((f) => `-- ===== ${f} =====\n` + fs.readFileSync(`supabase/migrations/${f}`, 'utf8')).join('\n'));

const counts = Object.fromEntries(areas.map((a) => [a.id, tables.filter((t) => t.area_id === a.id).length]));
console.log('tables per room:', counts, 'total', tables.length);
